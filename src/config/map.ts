import type { ItemType } from './balance.ts';

export interface Rect { x: number; y: number; w: number; h: number }
export interface LootSpawn { id: string; type: ItemType; x: number; y: number }
export interface NetSpawn { id: string; x: number; y: number; w: number; h: number; kind: 'thin' | 'thick' }
export interface CoralSpawn { x: number; y: number; w: number; h: number; flip?: boolean }
export type CreatureKind = 'fish' | 'fishBig' | 'dart';
export interface CreatureSpawn { kind: CreatureKind; x: number; y: number; minX?: number; maxX?: number; facing?: -1 | 1 }
export interface DecorSpawn { frame: string; x: number; y: number; flip?: boolean; alpha?: number }

const R = (x: number, y: number, w: number, h: number): Rect => ({ x, y, w, h });

/** Набор предметов одного типа: id = prefix-NN по порядку точек. */
function many(prefix: string, type: ItemType, pts: [number, number][]): LootSpawn[] {
  return pts.map(([x, y], i) => ({ id: `${prefix}-${String(i + 1).padStart(2, '0')}`, type, x, y }));
}

